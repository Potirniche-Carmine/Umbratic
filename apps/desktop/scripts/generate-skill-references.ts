write(
  "umbratic-pdf",
  "ops.md",
  `# PDF ops

All page-level or metadata-level. A PDF has no paragraph structure, so there is
no body-text rewrite — rebuild from source with \`create\` instead.

Page numbers are one-based, matching \`inspect\`.

${table(
  ["op", "arguments"],
  [
    ["merge", "`files[]` — workspace-relative PDFs, appended in order"],
    ["split", "`every` (pages per part); needs `out` to be a folder"],
    ["extractPages", "`pages[]`"],
    ["deletePages", "`pages[]`"],
    ["reorder", "`order[]` — every page exactly once"],
    ["rotate", "`angle` 90/180/270/-90, `pages[]` (omit for all)"],
    ["insertBlank", "`at`"],
    ["watermark", "`text`, `opacity`, `pages[]`"],
    ["stamp", "`text` or `image`, `corner`, `size`/`width`, `pages[]`"],
    ["fillForm", "`values {field: string | number | boolean}`"],
    ["flatten", "— one-way; the values become page content"],
    ["setMetadata", "`title`, `author`, `subject`"],
  ],
)}

## Rules

- A PDF must keep at least one page.
- \`reorder\` must list every page exactly once; a partial order is refused
  rather than silently dropping pages.
- \`fillForm\` fails naming the fields the document actually has.
- \`flatten\` is not reversible. Only do it when the user asks to finalise.
- An encrypted file is \`inspect-only\`; a scan is still \`surgical\`, because
  page operations work perfectly well on one.
`,
);

