/**
 * Generates the reference pages the artifact skills link to.
 *
 * The limits, layout names, block types, presets, and the formula allowlist all
 * live in exactly one place — the code that enforces them — and this reads them
 * from there. A reference page written by hand is a reference page that is
 * wrong the first time a limit changes, and a model that has been told the
 * wrong limit spends a round discovering it.
 *
 * Run with `npm run generate:skill-references`. It is checked in CI, so a limit
 * changed without regenerating fails the build rather than shipping a lie.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import { loadTypeScriptModule } from "../tests/helpers/load-ts-module.ts";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skillsRoot = path.join(desktopRoot, "src", "main", "system-skills");
const workerRoot = path.join(desktopRoot, "src", "main", "artifacts", "worker");

const cache = new Map();
const load = (relative: string) =>
  loadTypeScriptModule(path.join(workerRoot, relative), { cache, realm: "host" });

const pptxSpec = load("pptx/spec.ts");
const blockSpec = load("blocks/spec.ts");

const banner =
  "<!-- Generated by scripts/generate-skill-references.ts. Do not edit by hand. -->\n";

function write(skill: string, name: string, body: string): void {
  const directory = path.join(skillsRoot, skill, "references");
  fs.mkdirSync(directory, { recursive: true });
  const file = path.join(directory, name);
  fs.writeFileSync(file, `${banner}\n${body.trimEnd()}\n`, "utf8");
  console.log(`Wrote ${path.relative(desktopRoot, file)}`);
}

function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

