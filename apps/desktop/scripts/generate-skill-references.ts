write(
  "umbratic-presentations",
  "ops.md",
  `# PPTX ops

Addressed by slide number and shape name, both from \`inspect\`.

## Surgical — available on any deck that opened

${table(
  ["op", "arguments"],
  [
    ["replaceText", "`slide`, `shape`, `text`"],
    ["setBullets", "`slide`, `shape`, `bullets[]`"],
    ["setNotes", "`slide`, `notes`"],
    ["replaceImage", "`slide`, `shape`, `image`"],
    ["setChartData", "`slide`, `shape`, `chart {type, categories, series}`"],
    ["setTable", "`slide`, `shape`, `rows[][]`, `header`"],
    ["findReplace", "`find`, `replace`, `scope` (a slide number, or omit for all)"],
    ["duplicateSlide", "`slide`"],
    ["moveSlide", "`slide`, `to`"],
    ["deleteSlide", "`slide`"],
  ],
)}

## Full surface only — an Umbratic deck with nothing unsupported

${table(["op", "arguments"], [["insertSlide", "`at`, plus any \`create\` slide's fields"]])}

## Rules

- One bad op discards the whole batch; the file is untouched.
- \`setTable\` replaces cells and never adds rows.
- \`setChartData\` is validated by the same schema \`create\` uses.
- \`duplicateSlide\` is refused on a slide holding \`smart-art\` or \`ole\`:
  cloning those parts produces a deck PowerPoint reports as damaged.
- \`findReplace\` coalesces runs first, so it matches what the reader sees.
- A deck must keep at least one slide.
`,
);

